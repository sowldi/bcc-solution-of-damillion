# fmt: on

CRITERIA = MappingProxyType({item.code: item for item in _ALL})


def criterion(code: str) -> Criterion:
    try:
        return CRITERIA[code]
    except KeyError:
        raise KeyError(f"Неизвестный критерий качества: {code}") from None
