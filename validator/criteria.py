"""Критерии качества требований из стандартов — на них ссылаются правила и замечания.

ISO/IEC/IEEE 29148:2018: п. 5.2.5 — свойства отдельного требования (a–i), п. 5.2.6 — свойства
набора требований (a–e). IEEE 830-1998, п. 4.3 — свойства спецификации; отсюда взяты только
свойства, которых нет в 29148 (ранжирование, модифицируемость, трассируемость).
"""

from __future__ import annotations

from dataclasses import dataclass
from types import MappingProxyType

ISO_29148 = "ISO/IEC/IEEE 29148:2018"
IEEE_830 = "IEEE 830-1998"


@dataclass(frozen=True)
class Criterion:
    code: str
    standard: str
    clause: str
    title: str
    description: str

    @property
    def reference(self) -> str:
        """«ISO/IEC/IEEE 29148:2018, п. 5.2.5 g»."""
        return f"{self.standard}, п. {self.clause}"


