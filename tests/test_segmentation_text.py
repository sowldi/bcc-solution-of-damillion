def test_split_statements(text: str, expected: list[tuple[str, str]]) -> None:
    assert _parts(text) == expected


def test_statements_are_exact_stripped_slices_after_start() -> None:
    text = "Ф-1. Первое утверждение.   Второе утверждение. "
    body = parse_prefix(text, "list_item").body_start

    statements = split_statements(text, start=body)

    assert [text[s.start : s.end] for s in statements] == [
        "Первое утверждение.",
        "Второе утверждение.",
    ]
    assert all(s.start >= body for s in statements)


def test_find_references_resolves_known_targets() -> None:
    refs = find_references(
        "Порог задаётся как в Ф-2 (см. Ф-9), см. раздел 4.2 и «Требования к данным».",
        doc_ids={"Ф-1", "Ф-2"},
        headings=["Требования к данным", "4.1 Общие положения"],
        own_id="Ф-1",
    )

    assert refs == (
        "req:Ф-2",
        "unresolved:Ф-9",
        "unresolved:раздел 4.2",
        "section:Требования к данным",
    )


def test_locate_references_gives_exact_spans_in_text_order() -> None:
    text = "Порог задаётся как в Ф-2 (см. Ф-9), см. раздел 4.2 и «Требования к данным»."

    spans = locate_references(
        text,
        doc_ids={"Ф-1", "Ф-2"},
        headings=["Требования к данным", "4.1 Общие положения"],
        own_id="Ф-1",
    )

    assert [(s.label, text[s.start : s.end]) for s in spans] == [
        ("req:Ф-2", "Ф-2"),
        ("unresolved:Ф-9", "Ф-9"),
        ("unresolved:раздел 4.2", "раздел 4.2"),
        ("section:Требования к данным", "«Требования к данным»"),
    ]


def test_find_references_resolves_section_numbers_and_ignores_own_id() -> None:
    refs = find_references(
        "Ф-1 описан выше, детали в разделе 4.1.",
        doc_ids={"Ф-1"},
        headings=["4.1 Общие положения"],
        own_id="Ф-1",
    )

    assert refs == ("section:4.1 Общие положения",)
